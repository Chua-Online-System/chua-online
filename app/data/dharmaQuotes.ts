export function getTodayQuote(): DharmaQuote {
  const now = new Date()
  const start = new Date(now.getFullYear(), 0, 0)
  const diff = now.getTime() - start.getTime()
  const oneDay = 1000 * 60 * 60 * 24
  const dayOfYear = Math.floor(diff / oneDay)
  const index = Math.abs(dayOfYear) % DHARMA_QUOTES.length
  return DHARMA_QUOTES[index]
}

export function getRandomQuote(): DharmaQuote {
  const index = Math.floor(Math.random() * DHARMA_QUOTES.length)
  return DHARMA_QUOTES[index]
}

